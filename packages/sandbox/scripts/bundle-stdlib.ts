/**
 * Bundles src/stdlib-entry.js (lodash, dayjs + plugins) into one IIFE and writes it to src/stdlib.generated.ts.
 * The bundle is committed so the runtime never needs esbuild or a source path (the server is itself bundled).
 *   pnpm --filter @ow/sandbox bundle:stdlib
 * test/stdlib.test.ts fails when the committed file is out of date (e.g. after bumping lodash or dayjs).
 */
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { buildSync } from 'esbuild'

const srcDir = join(dirname(fileURLToPath(import.meta.url)), '../src')
export const generatedPath = join(srcDir, 'stdlib.generated.ts')

export function renderGeneratedStdlib(): string {
  const result = buildSync({
    entryPoints: [join(srcDir, 'stdlib-entry.js')],
    bundle: true,
    format: 'iife',
    platform: 'neutral',
    mainFields: ['module', 'main'],
    target: 'es2022',
    minify: true,
    legalComments: 'none',
    write: false,
    logLevel: 'silent',
  })
  const bundle = result.outputFiles[0]!.text
  return [
    '// Generated by scripts/bundle-stdlib.ts from src/stdlib-entry.js. Do not edit; re-run the script instead.',
    `export const STDLIB_BUNDLE = ${JSON.stringify(bundle)}`,
    '',
  ].join('\n')
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(generatedPath, renderGeneratedStdlib())
  console.log(`Wrote ${generatedPath}`)
}
